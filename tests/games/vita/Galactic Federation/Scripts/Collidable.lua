  function Collidable:DrawCollisionBoxes()
  
  for y = 1, #self.array, 1 do
    xLength = 0
    yLength = 0
  
    for x = 1, #self.array[y], 1 do
    
  xLength = 0
  yLength = 0
    
      if(self.array[y][x] == 1) then
      
        for n = x , #self.array[y], 1 do
          
          if(self.array[y][n] == 1) then
            xLength = xLength + 1
          else
            break
          end
          
          
        end
        
        for n = y, #self.array, 1 do
          
          if(self.array[n][x] == 1) then
            yLength = yLength + 1  
          else
            break
          end
          
        end
        
        if(xLength > 0 or yLength > 0) then
        
          if(xLength >= yLength) then
            table.insert(collidableObj , #collidableObj + 1, RectangleCollision:New((self.xRange + x - 2) * 32, (self.yRange + y - 2 ) * 32, xLength, 1))
            
            for n = x, x + xLength, 1 do
                self.array[y][n] = 0
            end
            
            
          end
          
          if(yLength > xLength) then
            table.insert(collidableObj , #collidableObj + 1, RectangleCollision:New((self.xRange + x - 2 ) * 32, (self.yRange + y - 2 ) * 32, 1, yLength))
            
             for n = y, y + yLength, 1 do
                self.array[n][x] = 0
            end
          end
        end
      
      
      end
    
    
    end
    
    
  end
  
  
end








